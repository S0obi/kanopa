import { beforeEach, describe, expect, it } from "vitest";
import { screen, waitFor, within } from "@testing-library/react";
import { FAKE, createFakeBackend, sampleConnections } from "@/api/fake";
import { fakeRules, resetFakeDirectory } from "@/api/fakeDirectory";
import { renderWith } from "@/test/render";
import { useApp } from "@/stores/app";
import { useToasts } from "@/ui";
import { BrowserScreen } from "./BrowserScreen";
import { useChanges } from "./changes";

// A password Kanopa generates: shown in plain text, copied with a countdown, kept only until applied.

async function openAda() {
  const backend = createFakeBackend({ connections: sampleConnections() });
  const r = await backend.connect("prod", "", false);
  useApp.setState({ view: { name: "connected", session: r.session! } });
  const out = renderWith(<BrowserScreen session={r.session!} />, backend);
  await out.user.click(await screen.findByRole("treeitem", { name: /^ou=people/ }));
  await out.user.keyboard("{ArrowRight}");
  await out.user.click(await screen.findByRole("treeitem", { name: /^uid=ada / }));
  await screen.findByRole("heading", { level: 1, name: "Ada Lovelace" });
  return { ...out, backend };
}
type Opened = Awaited<ReturnType<typeof openAda>>;

const table = () => screen.getByRole("table", { name: "Attributes" });
const bar = () => screen.getByRole("region", { name: "Pending changes" });

beforeEach(() => {
  FAKE.delayMs = 0;
  FAKE.lost = false;
  resetFakeDirectory();
  useChanges.setState({ byConnection: {} });
  useToasts.setState({ toasts: [] });
});

async function generateInEditor(user: Opened["user"]) {
  await user.click(within(table()).getByRole("button", { name: "Edit userPassword" }));
  const dialog = screen.getByRole("dialog", { name: /Edit userPassword/ });
  await user.click(within(dialog).getByRole("button", { name: "Generate a password" }));
  return dialog;
}

describe("the password generator", () => {
  it("fills the field in plain text, hides the confirmation, and copies with a countdown", async () => {
    const { user, backend } = await openAda();
    const d = await generateInEditor(user);
    const field = within(d).getByLabelText("New password");
    const value = (field as HTMLInputElement).value;
    expect(value).toHaveLength(20);
    expect(field).toHaveAttribute("type", "text");
    expect(within(d).queryByLabelText("Confirm password")).not.toBeInTheDocument();
    expect(within(d).queryByRole("button", { name: "Show password" })).not.toBeInTheDocument();
    expect(within(d).getByText(/^Generated by Kanopa: 20 characters\./)).toBeInTheDocument();

    await user.click(within(d).getByRole("button", { name: "Copy password" }));
    expect(backend.clipboard.text).toBe(value);
    expect(await within(d).findByText(/^Copied\. Clears from the clipboard in 60 s\. Clipboard history or sync may keep a copy\./)).toBeInTheDocument();
    expect(within(d).getByRole("button", { name: "Copied" })).toBeInTheDocument();

    // Another one replaces it; typing returns to a masked field that asks twice.
    await user.click(within(d).getByRole("button", { name: "Generate another password" }));
    expect((within(d).getByLabelText("New password") as HTMLInputElement).value).not.toBe(value);
    await user.type(within(d).getByLabelText("New password"), "x");
    expect(within(d).getByLabelText("New password")).toHaveAttribute("type", "password");
    expect(within(d).getByLabelText("Confirm password")).toBeInTheDocument();
    expect(within(d).queryByRole("button", { name: "Copy password" })).not.toBeInTheDocument();
  });

  it("is offered to copy from the changes bar and the entry until it is applied, then once in the notice", async () => {
    const { user, backend } = await openAda();
    const d = await generateInEditor(user);
    const value = (within(d).getByLabelText("New password") as HTMLInputElement).value;
    await user.click(within(d).getByRole("button", { name: "Add to changes" }));
    expect(screen.queryByRole("dialog", { name: /Edit userPassword/ })).not.toBeInTheDocument();
    expect(document.body.textContent).not.toContain(value);

    // From the changes bar, and from the entry's own banner.
    expect(screen.getByText("New password waiting.")).toBeInTheDocument();
    await user.click(within(bar()).getByRole("button", { name: "Copy password" }));
    expect(backend.clipboard.text).toBe(value);
    backend.clipboard.text = "";
    const inBanner = screen.getAllByRole("button", { name: /^Copy password$|^Copied$/ }).filter((b) => !bar().contains(b));
    expect(inBanner).toHaveLength(1);
    await user.click(inBanner[0]!);
    expect(backend.clipboard.text).toBe(value);

    await user.click(within(bar()).getByRole("button", { name: /Apply/ }));
    expect(await screen.findByText("Ada Lovelace has a new password. Kanopa forgets it when this notice closes.")).toBeInTheDocument();
    expect(screen.queryByText(/^Saved 1 change/)).not.toBeInTheDocument();
    backend.clipboard.text = "";
    await user.click(screen.getByRole("button", { name: "Copy password for Ada Lovelace" }));
    expect(backend.clipboard.text).toBe(value);

    await user.click(screen.getByRole("button", { name: "Close notice" }));
    expect(screen.queryByText(/has a new password/)).not.toBeInTheDocument();
    expect(document.body.textContent).not.toContain(value);
    expect(screen.queryByRole("region", { name: "Pending changes" })).not.toBeInTheDocument();
  });

  it("offers no Copy for a password the person typed", async () => {
    const { user } = await openAda();
    await user.click(within(table()).getByRole("button", { name: "Edit userPassword" }));
    const d = screen.getByRole("dialog", { name: /Edit userPassword/ });
    await user.type(within(d).getByLabelText("New password"), "typed-Passw0rd");
    await user.type(within(d).getByLabelText("Confirm password"), "typed-Passw0rd");
    await user.click(within(d).getByRole("button", { name: "Add to changes" }));
    expect(screen.queryByText("New password waiting.")).not.toBeInTheDocument();
    expect(within(bar()).queryByRole("button", { name: "Copy password" })).not.toBeInTheDocument();
    await user.click(within(bar()).getByRole("button", { name: /Apply/ }));
    expect(await screen.findByText(/^Saved 1 change to localhost\./)).toBeInTheDocument();
    expect(screen.queryByText(/has a new password/)).not.toBeInTheDocument();
  });

  it("says so when the server refuses a generated password, and keeps it pending", async () => {
    const { user } = await openAda();
    const d = await generateInEditor(user);
    await user.click(within(d).getByRole("button", { name: "Add to changes" }));
    fakeRules.refusePasswords = true;
    await user.click(within(bar()).getByRole("button", { name: /Apply/ }));
    expect(await screen.findByText(/Kanopa generated this password\. The server's rules may need something else: type one, or generate another\./)).toBeInTheDocument();
    expect(screen.queryByText(/has a new password/)).not.toBeInTheDocument();
    await waitFor(() => expect(within(bar()).getByRole("button", { name: "Copy password" })).toBeInTheDocument());
  });

  it("is on a new person's initial password too, and the person is listed for Copy after Apply", async () => {
    const { user, backend } = await openAda();
    await user.click(await screen.findByRole("treeitem", { name: /^ou=people/ }));
    await screen.findByRole("heading", { level: 1, name: "people" });
    await user.click(screen.getByRole("button", { name: "New entry" }));
    const d = screen.getByRole("dialog", { name: "New entry" });
    await user.type(within(d).getByLabelText(/First name/), "Mary");
    await user.type(within(d).getByLabelText(/Last name/), "Jackson");
    await user.click(within(d).getByRole("button", { name: "Generate a password" }));
    const value = (within(d).getByLabelText(/Initial password/) as HTMLInputElement).value;
    expect(value).toHaveLength(20);
    await user.click(within(d).getByRole("button", { name: "Create entry" }));
    await user.click(within(bar()).getByRole("button", { name: /Apply/ }));
    expect(await screen.findByText("Mary Jackson has a new password. Kanopa forgets it when this notice closes.")).toBeInTheDocument();
    await user.click(screen.getByRole("button", { name: "Copy password for Mary Jackson" }));
    expect(backend.clipboard.text).toBe(value);
  });
});
